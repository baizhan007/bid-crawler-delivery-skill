def parse_fixture(bundle):
    """Convert recorded responses into normalized bid records.

    Replace the generic parser with site-specific list/detail joining when needed.
    """

    records = []
    for response in bundle:
        if response.body_path.suffix.lower() != ".json" and "json" not in response.content_type.lower():
            continue
        payload = response.json()
        candidates = payload.get("rows") or payload.get("records") or payload.get("items") or []
        if isinstance(candidates, list):
            records.extend(dict(item) for item in candidates if isinstance(item, dict))
    return records
